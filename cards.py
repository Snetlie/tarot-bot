import secrets

MAJOR = [
    "Шут", "Маг", "Верховная Жрица", "Императрица", "Император", "Иерофант",
    "Влюблённые", "Колесница", "Сила", "Отшельник", "Колесо Фортуны",
    "Справедливость", "Повешенный", "Смерть", "Умеренность", "Дьявол", "Башня",
    "Звезда", "Луна", "Солнце", "Суд", "Мир",
]
SUITS = ["Жезлов", "Кубков", "Мечей", "Пентаклей"]
RANKS = [
    "Туз", "Двойка", "Тройка", "Четвёрка", "Пятёрка", "Шестёрка", "Семёрка",
    "Восьмёрка", "Девятка", "Десятка", "Паж", "Рыцарь", "Королева", "Король",
]
DECK = MAJOR + [f"{r} {s}" for s in SUITS for r in RANKS]

SPREADS = {
    "day": {"name": "Карта дня", "positions": ["Совет дня"]},
    "three": {"name": "Прошлое — Настоящее — Будущее",
              "positions": ["Прошлое", "Настоящее", "Будущее"]},
    "advice": {"name": "Ситуация — Препятствие — Совет",
               "positions": ["Ситуация", "Препятствие", "Совет"]},
    "celtic": {"name": "Кельтский крест",
               "positions": ["Суть ситуации", "Препятствие", "Основа", "Прошлое",
                             "Возможное будущее", "Ближайшее будущее", "Вы сами",
                             "Окружение", "Надежды и страхи", "Итог"]},
}


def draw(spread_id):
    spread = SPREADS[spread_id]
    deck = DECK[:]
    for i in range(len(deck) - 1, 0, -1):
        j = secrets.randbelow(i + 1)
        deck[i], deck[j] = deck[j], deck[i]
    return [
        {"position": pos, "name": deck[i], "reversed": secrets.randbelow(3) == 0}
        for i, pos in enumerate(spread["positions"])
    ]
